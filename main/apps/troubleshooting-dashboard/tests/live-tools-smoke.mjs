import assert from 'node:assert/strict';
import { chromium } from '../../../tools/playwright-smoke/node_modules/playwright/index.mjs';
import { mkdir } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';

const url = process.env.POC_URL || 'https://homepage.home.local/portal-preview/troubleshooting/';
const output = path.join(os.tmpdir(), 'troubleshooting-live-tools');
await mkdir(output, { recursive: true });
const browser = await chromium.launch();
const errors = [];
try {
  const page = await browser.newPage({ ignoreHTTPSErrors: true, viewport: { width: 1440, height: 1000 } });
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(url);
  await page.waitForFunction(() => document.querySelector('#resource-rows').children.length >= 6);
  assert.match(await page.locator('#resource-status').textContent(), /Fresh coverage/);
  await page.locator('a[href="#route=monitoring"]').click();
  await page.locator('.step-body').first().evaluate(element => { element.open = true; });
  const routeProbe = page.getByRole('button', { name: 'Test TCP 192.168.60.10:3000 from VM103' });
  await routeProbe.click();
  await page.waitForFunction(() => document.querySelector('#console-output').textContent.includes('tcp monitoring 3000'));
  assert.match(await page.locator('#active-status').textContent(), /Needs evidence/);
  assert.equal(await page.locator('#probe-target option').count(), 9);
  await page.locator('#probe-target').selectOption('docker');
  await page.locator('[data-probe="ping"]').click();
  await page.waitForFunction(() => document.querySelector('#console-output').textContent.includes('ping docker'));
  assert.match(await page.locator('#console-output').textContent(), /PASS/);
  await page.locator('[data-probe="dns"]').click();
  await page.waitForFunction(() => document.querySelector('#console-output').textContent.includes('System resolver lookup: homepage.home.local'));
  await page.locator('#probe-port').selectOption('8094');
  await page.locator('[data-probe="tcp"]').click();
  await page.waitForFunction(() => document.querySelector('#console-output').textContent.includes('tcp docker 8094'));
  await page.locator('#console-command').fill('http docker');
  await page.locator('#console-run').click();
  await page.waitForFunction(() => document.querySelector('#console-output').textContent.includes('HTTP 200'));
  await page.locator('#console-command').fill('ping 1.1.1.1; id');
  await page.locator('#console-run').click();
  await page.waitForFunction(() => document.querySelector('#console-state').textContent.includes('supported action'));
  assert.doesNotMatch(await page.locator('#console-output').textContent(), /1\.1\.1\.1/);
  const forbidden = await page.evaluate(async () => (await fetch('./api/probe', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: '{"command":"ping docker"}' })).status);
  assert.equal(forbidden, 403);
  await page.screenshot({ path: path.join(output, 'desktop.png'), fullPage: true });
  await page.locator('#connection-tests').scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(output, 'console.png') });
  await page.route('**/api/resources', route => route.fulfill({ json: { snapshot: { timestamp: Date.now() / 1000 - 600, samples: { host: { available_pct: 80, available_mib: 20000 } }, expected: [] }, status: {} } }));
  await page.locator('#refresh-resources').click();
  await page.waitForFunction(() => document.querySelector('#resource-status').textContent.includes('Stale'));
  assert.match(await page.locator('#resource-status').textContent(), /unknown/);
  await page.route('**/api/resources', route => route.fulfill({ status: 503, json: { error: 'Monitor unavailable' } }));
  await page.locator('#refresh-resources').click();
  await page.waitForFunction(() => document.querySelector('#resource-status').textContent.includes('Unavailable'));
  assert.equal(await page.locator('#resource-rows tr').count(), 0);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.unroute('**/api/resources');
  await page.locator('#refresh-resources').click();
  await page.waitForFunction(() => document.querySelector('#resource-rows').children.length >= 6);
  await page.locator('#resource-health').scrollIntoViewIfNeeded();
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: path.join(output, 'mobile.png'), fullPage: true });
  await page.screenshot({ path: path.join(output, 'mobile-viewport.png') });
  await page.locator('#console-command').focus();
  await page.keyboard.press('Tab');
  assert.equal(await page.locator('#console-run').evaluate(element => element === document.activeElement), true);
  assert.deepEqual(errors, []);
  if (url.startsWith('https://homepage.home.local/')) {
    const homepage = await browser.newPage({ ignoreHTTPSErrors: true });
    await homepage.goto('https://homepage.home.local/#monitoring');
    const card = homepage.locator('#portal-resource-health');
    await card.waitFor({ state: 'visible', timeout: 15000 });
    assert.ok(await card.locator('a[href*="#resource-health"]').count());
    await card.locator('.portal-preview-trigger').click();
    const frame = homepage.frameLocator('.portal-preview-frame');
    await frame.locator('#resource-status').filter({ hasText: 'Fresh coverage' }).waitFor();
    await homepage.close();
  }
  console.log(`Live tools browser checks passed. Screenshots: ${output}`);
} finally { await browser.close(); }
