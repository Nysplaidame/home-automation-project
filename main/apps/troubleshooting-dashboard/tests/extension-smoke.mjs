import assert from 'node:assert/strict';
import { chromium } from '../../../tools/playwright-smoke/node_modules/playwright/index.mjs';
import { mkdir } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';

const url = process.env.POC_URL || 'https://homepage.home.local/portal-preview/troubleshooting/';
const output = path.join(os.tmpdir(), 'troubleshooting-extension');
await mkdir(output, { recursive: true });
const browser = await chromium.launch();
const errors = [];
try {
  const page = await browser.newPage({ ignoreHTTPSErrors: true, viewport: { width: 1440, height: 1000 } });
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(url);
  await page.waitForFunction(() => document.querySelector('#bundle-select').options.length === 9);
  await page.locator('#probe-target').selectOption('docker');
  await page.locator('#probe-tls').click();
  await page.waitForFunction(() => document.querySelector('#console-output').textContent.includes('Legacy compatibility: chain, hostname and dates verified'));
  assert.match(await page.locator('#console-output').textContent(), /WARNING/);
  await page.locator('#bundle-select').selectOption('portal');
  await page.locator('#bundle-run').click();
  await page.waitForFunction(() => document.querySelector('#bundle-state').textContent.includes('Bundle complete'), { timeout: 45000 });
  assert.match(await page.locator('#bundle-state').textContent(), /4\/4 checks · 0 failures · 1 warnings · 0 unknown/);
  assert.match(await page.locator('#active-status').textContent(), /Needs evidence/);
  await page.evaluate(() => { location.hash = 'route=camera'; });
  await page.waitForFunction(() => document.querySelector('#bundle-select').value === 'camera');
  await page.locator('a[href="#incident-history"]').click();
  await page.locator('#refresh-history').click();
  await page.waitForFunction(() => document.querySelector('#history-events').textContent.includes('tls docker'));
  const first = page.locator('#history-events details').first();
  await first.locator('summary').click();
  const link = new URL(await first.getByRole('link', { name: 'Grafana resources' }).getAttribute('href'));
  assert.equal(Number(link.searchParams.get('to')) - Number(link.searchParams.get('from')), 1200000);
  assert.equal(link.hostname, 'homepage.home.local');
  assert.ok(link.pathname.includes('/d/infrastructure-fleet/'));
  await page.locator('#history-filter').selectOption('diagnostic');
  assert.match(await page.locator('#history-events').textContent(), /tls docker/);
  await page.screenshot({ path: path.join(output, 'desktop-history.png') });

  const commands = [];
  await page.route('**/api/probe', async route => {
    const { command } = route.request().postDataJSON();
    commands.push(command);
    await new Promise(resolve => setTimeout(resolve, 300));
    await route.fulfill({ json: { command, target: 'frigate', timestamp: Date.now() / 1000, source: 'VM103 test fixture', ok: true, severity: 'pass', duration_ms: 300, output: 'Fixture connection result' } });
  });
  await page.locator('#bundle-run').click();
  await page.locator('#bundle-stop').click();
  await page.waitForFunction(() => document.querySelector('#bundle-state').textContent.startsWith('Stopped'));
  assert.equal(commands.length, 1);
  assert.match(await page.locator('#bundle-state').textContent(), /1\/4 checks/);
  commands.length = 0;
  await page.unroute('**/api/probe');
  await page.route('**/api/probe', async route => {
    const { command } = route.request().postDataJSON();
    commands.push(command);
    await route.fulfill({ json: { command, target: 'frigate', timestamp: Date.now() / 1000, source: 'VM103 test fixture', ok: commands.length > 1, severity: commands.length > 1 ? 'pass' : 'fail', duration_ms: 1, output: 'Fixture check result' } });
  });
  await page.locator('#bundle-run').click();
  await page.waitForFunction(() => document.querySelector('#bundle-state').textContent.startsWith('Bundle complete'));
  assert.equal(commands.length, 4);
  assert.match(await page.locator('#bundle-state').textContent(), /1 failures/);
  await page.unroute('**/api/probe');
  await page.route('**/api/events', route => route.fulfill({ status: 503, json: { error: 'Event history unavailable' } }));
  await page.locator('#refresh-history').click();
  await page.waitForFunction(() => document.querySelector('#history-state').textContent.includes('out of date'));
  await page.unroute('**/api/events');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('#connection-tests').scrollIntoViewIfNeeded();
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: path.join(output, 'mobile-tools.png'), fullPage: true });
  await page.locator('#incident-history').scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(output, 'mobile-history.png') });
  const unlabeled = await page.evaluate(() => [...document.querySelectorAll('button,input,select,textarea')].filter(element => !(element.getAttribute('aria-label') || element.textContent || element.getAttribute('placeholder') || element.labels?.length)).map(element => element.id));
  assert.deepEqual(unlabeled, []);
  assert.deepEqual(errors, []);
  console.log(`TLS, bundles and history browser checks passed. Screenshots: ${output}`);
} finally { await browser.close(); }
