"""Generate the dashboard's expected mode states from canonical HA scripts.

No connection to HA or MQTT. The generated module is a selected release asset.
"""
import json
import subprocess
from pathlib import Path
import yaml
from ventsys_operating_modes import STATES, REQUESTS, transition, TEST_TARGETS

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'ventsys/ventsys_bundle_updated/ventsys_ha_scripts.yaml'
TOPICS = {
    'ventsys/main/valve1/control': 'main1', 'ventsys/main/valve2/control': 'main2',
    'ventsys/fdm/branch/control': 'fdm_branch', 'ventsys/fdm/valve/control': 'fdm_print', 'ventsys/sla/360/control': 'fdm_360',
    'ventsys/sla/branch/control': 'sla_branch', 'ventsys/sla/valve/control': 'sla_print', 'ventsys/fdm/360/control': 'sla_360',
    'ventsys/fan/control': 'fan_main', 'ventsys/fan/percent': 'fan_main_speed',
    'ventsys/spray-fan/control': 'fan_booth', 'ventsys/spray-fan/percent': 'fan_booth_speed',
}

def expected_modes():
    scripts = yaml.safe_load(SOURCE.read_text(encoding='utf-8'))['script']
    def expand(name, seen=()):
        if name in seen:
            raise ValueError('Recursive mode script')
        result = {}
        def walk(node):
            if isinstance(node, list):
                for entry in node:
                    walk(entry)
            elif isinstance(node, dict):
                action = node.get('action', '')
                data = node.get('data', {})
                if action == 'script.ventsys_ramp_valve':
                    key = TOPICS[data['topic']]
                    # Accepted 360 firmware clamps the existing logical mode
                    # targets 0/100 to its correct closed/open targets 30/60.
                    # This contract describes reported state, not the raw
                    # MQTT payload; the HA mode scripts stay unchanged.
                    result[key] = {0: 30, 100: 60}.get(data['target'], data['target']) if key.endswith('_360') else data['target']
                elif action == 'mqtt.publish':
                    raw = str(data['payload'])
                    result[TOPICS[data['topic']]] = raw if raw in ('on', 'off') else int(raw)
                elif action.startswith('script.ventsys_mode_'):
                    result.update(expand(action.removeprefix('script.'), seen + (name,)))
                for key in ('sequence', 'parallel'):
                    if key in node:
                        walk(node[key])
        walk(scripts[name]['sequence'])
        return result
    return {name.removeprefix('ventsys_mode_'): expand(name) for name in scripts
            if name.startswith('ventsys_mode_') and name != 'ventsys_mode_fire_safe'}

